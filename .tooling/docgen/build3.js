const fs = require("fs");
const {
  Document, Packer, Paragraph, TextRun, HeadingLevel,
  Table, TableRow, TableCell, WidthType, ShadingType, BorderStyle,
  Footer, PageNumber, AlignmentType, PageBreak, TableOfContents,
} = require("docx");

const FONT = "微软雅黑";
const MONO = "Consolas";
const BODY = 21;
const SMALL = 19;

const p = (text, opts = {}) =>
  new Paragraph({
    spacing: { after: opts.after ?? 120, line: 320 },
    children: [new TextRun({ text, font: opts.font ?? FONT, size: opts.size ?? BODY, bold: !!opts.bold, color: opts.color ?? "222222" })],
  });

const code = (text) =>
  new Paragraph({
    spacing: { before: 60, after: 140, line: 260 },
    shading: { type: ShadingType.CLEAR, color: "auto", fill: "F4F4F4" },
    indent: { left: 240, right: 240 },
    children: [new TextRun({ text, font: MONO, size: 17, color: "333333" })],
  });

const h1 = (text) =>
  new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 360, after: 160 },
    children: [new TextRun({ text, font: FONT, size: 32, bold: true, color: "1F3864" })],
  });

const h2 = (text) =>
  new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 240, after: 100 },
    children: [new TextRun({ text, font: FONT, size: 25, bold: true, color: "2E5496" })],
  });

const h3 = (text) =>
  new Paragraph({
    heading: HeadingLevel.HEADING_3,
    spacing: { before: 180, after: 80 },
    children: [new TextRun({ text, font: FONT, size: 22, bold: true, color: "3A6BAA" })],
  });

const bullet = (text) =>
  new Paragraph({
    bullet: { level: 0 },
    spacing: { after: 80, line: 320 },
    children: [new TextRun({ text, font: FONT, size: BODY, color: "222222" })],
  });

const numbered = (n, text) =>
  new Paragraph({
    spacing: { after: 80, line: 320 },
    indent: { left: 360, hanging: 360 },
    children: [new TextRun({ text: `${n}. ${text}`, font: FONT, size: BODY, color: "222222" })],
  });

const cell = (text, header, width) =>
  new TableCell({
    width: { size: width, type: WidthType.PERCENTAGE },
    shading: header ? { type: ShadingType.CLEAR, color: "auto", fill: "E8EEF7" } : undefined,
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [new Paragraph({ spacing: { after: 0, line: 280 }, children: [new TextRun({ text, font: FONT, size: SMALL, bold: header, color: header ? "1F3864" : "222222" })] })],
  });

const table = (rows, widths) =>
  new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: "BFBFBF" },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: "BFBFBF" },
      left: { style: BorderStyle.SINGLE, size: 4, color: "BFBFBF" },
      right: { style: BorderStyle.SINGLE, size: 4, color: "BFBFBF" },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 2, color: "D9D9D9" },
      insideVertical: { style: BorderStyle.SINGLE, size: 2, color: "D9D9D9" },
    },
    rows: rows.map((row, i) => new TableRow({ children: row.map((c, j) => cell(c, i === 0, widths[j])) })),
  });

const spacer = () => new Paragraph({ spacing: { after: 60 }, children: [] });

const cover = (title, subtitle, note) => [
  new Paragraph({ spacing: { before: 240, after: 80 }, children: [new TextRun({ text: title, font: FONT, size: 44, bold: true, color: "1F3864" })] }),
  new Paragraph({ spacing: { after: 120 }, children: [new TextRun({ text: subtitle, font: FONT, size: 20, color: "7F7F7F" })] }),
  new Paragraph({ spacing: { after: 240 }, shading: { type: ShadingType.CLEAR, color: "auto", fill: "F2F5FA" }, children: [new TextRun({ text: note, font: FONT, size: 19, color: "555555" })] }),
];

// 目录页：真正的 Word 目录域，收录一级与二级标题；页码由 Word/WPS 更新域时填入
const tocPage = () => [
  new Paragraph({ children: [new PageBreak()] }),
  new Paragraph({
    spacing: { after: 200 },
    children: [new TextRun({ text: "目录", font: FONT, size: 32, bold: true, color: "1F3864" })],
  }),
  new TableOfContents("目录", { hyperlink: true, headingStyleRange: "1-2" }),
  new Paragraph({ children: [new PageBreak()] }),
];

const pageFooter = () =>
  new Footer({
    children: [
      new Paragraph({
        alignment: AlignmentType.CENTER,
        children: [
          new TextRun({ text: "第 ", font: FONT, size: SMALL, color: "8C8C8C" }),
          new TextRun({ children: [PageNumber.CURRENT], font: FONT, size: SMALL, color: "8C8C8C" }),
          new TextRun({ text: " 页", font: FONT, size: SMALL, color: "8C8C8C" }),
        ],
      }),
    ],
  });

const tocStyle = (level) => ({
  id: `TOC${level}`,
  name: `toc ${level}`,
  basedOn: "Normal",
  next: "Normal",
  quickFormat: true,
  run: { font: FONT, size: BODY, color: "222222" },
  paragraph: { spacing: { after: 80, line: 300 }, indent: { left: (level - 1) * 200 } },
});

const finish = (children, out) => {
  const doc = new Document({
    features: { updateFields: true },
    styles: {
      default: { document: { run: { font: FONT, size: BODY } } },
      paragraphStyles: [tocStyle(1), tocStyle(2)],
    },
    sections: [{
      properties: {
        page: {
          size: { width: 11906, height: 16838 },
          margin: { top: 1440, bottom: 1440, left: 1440, right: 1440 },
        },
      },
      footers: { default: pageFooter() },
      children,
    }],
  });
  return Packer.toBuffer(doc).then((buf) => {
    fs.writeFileSync(out, buf);
    console.log("written:", out, buf.length, "bytes");
  });
};

